import { createHash } from 'node:crypto';
import {
	mkdir,
	readFile,
	readdir,
	rename,
	rm,
	writeFile,
} from 'node:fs/promises';
import { basename, dirname, resolve } from 'node:path';

const ASSET_HASH_LENGTH = 12;
const CATEGORIES = ['clothes', 'partners', 'special_guest'] as const;

const projectPath = resolve(import.meta.dirname, '../../..');
const tachiesPath = resolve(projectPath, 'public/assets/tachies');
const hashesPath = resolve(
	projectPath,
	'app/domain/data/tachies/assetHashes.ts'
);
const isDryRun = process.argv.includes('--dry-run');

interface IFileEntry {
	name: string;
	path: string;
}

async function listFiles(directory: string): Promise<IFileEntry[]> {
	const entries = await readdir(directory, { withFileTypes: true });
	const files: IFileEntry[] = [];
	for (const entry of entries) {
		const path = resolve(directory, entry.name);
		if (entry.isDirectory()) {
			files.push(...(await listFiles(path)));
		} else if (entry.isFile() && !entry.name.startsWith('.')) {
			files.push({ name: basename(path), path });
		}
	}
	return files;
}

async function hashCategory(category: (typeof CATEGORIES)[number]) {
	const categoryPath = resolve(tachiesPath, category);
	const files = await listFiles(categoryPath);
	if (files.length === 0) {
		throw new Error(`No tachie files found in ${categoryPath}`);
	}

	const filesByName = new Map<string, IFileEntry>();
	for (const file of files) {
		if (filesByName.has(file.name)) {
			throw new Error(
				`Duplicate tachie file ${file.name} in ${categoryPath}; remove the stale hashed copy first`
			);
		}
		filesByName.set(file.name, file);
	}

	const sortedFiles = [...filesByName.values()].sort((left, right) =>
		left.name < right.name ? -1 : left.name > right.name ? 1 : 0
	);
	const digest = createHash('sha256');
	for (const file of sortedFiles) {
		digest.update(file.name);
		digest.update('\0');
		digest.update(await readFile(file.path));
	}
	const hash = digest.digest('hex').slice(0, ASSET_HASH_LENGTH);

	if (!isDryRun) {
		const destination = resolve(categoryPath, hash);
		await mkdir(destination, { recursive: true });
		for (const file of sortedFiles) {
			const destinationFile = resolve(destination, file.name);
			if (destinationFile === file.path) {
				continue;
			}
			await rm(destinationFile, { force: true });
			await rename(file.path, destinationFile);
		}
		const entries = await readdir(categoryPath, { withFileTypes: true });
		for (const entry of entries) {
			if (entry.name !== hash) {
				await rm(resolve(categoryPath, entry.name), {
					force: true,
					recursive: true,
				});
			}
		}
	}

	return { category, fileCount: sortedFiles.length, hash };
}

async function writeHashes(
	hashes: ReadonlyArray<{
		category: (typeof CATEGORIES)[number];
		hash: string;
	}>
) {
	const lines = hashes.map(
		({ category, hash }) => `\t${category}: '${hash}',`
	);
	const content = `/** @description Generated by \`scripts/assets/tachies/hashTachies.ts\`. Do not edit by hand. */\nexport const TACHIE_ASSET_HASHES = {\n${lines.join('\n')}\n} as const;\n\nexport type TTachieAssetCategory = keyof typeof TACHIE_ASSET_HASHES;\n`;
	await mkdir(dirname(hashesPath), { recursive: true });
	await writeFile(hashesPath, content, 'utf8');
}

if (process.argv.includes('--help')) {
	console.log(`Usage: pnpm tachies:hash [--dry-run]

Manually maintained tachies are stored under public/assets/tachies/<category>/.
This command moves them into a content-hash directory and regenerates
app/domain/data/tachies/assetHashes.ts. Run it again after updating a file.

--dry-run  Print the resulting hashes without moving files.`);
} else {
	const hashes = [];
	for (const category of CATEGORIES) {
		const result = await hashCategory(category);
		hashes.push(result);
		console.log(
			`${result.category}: ${result.fileCount} files -> ${result.hash}`
		);
	}
	if (!isDryRun) {
		await writeHashes(hashes);
	}
}
